import type { Module } from "../module-binable.ts";
import { isFunctionType, type FunctionType, type ValueType } from "../types.ts";

export { exportTypes, entryTypes, isIdentifier };

function isIdentifier(name: string) {
  return /^[A-Za-z_$][\w$]*$/.test(name);
}

/** Declarations of the entry module: async exports return promises, others are the Wasm exports. */
function entryTypes(module: Module, asyncExports: string[], wasm: string): string {
  const lines = ["// Generated by wasmati build: async exports return promises."];
  const declarations = exportDeclarations(module);
  for (const [i, { name }] of module.exports.entries()) {
    if (!asyncExports.includes(name)) {
      lines.push(`export { ${exportName(name)} } from ${JSON.stringify(wasm)};`);
      continue;
    }
    const { local, params, results } = declarations[i] as FunctionDeclaration;
    lines.push(
      `declare function ${local}(${params}): Promise<${results}>;`,
      exportList(local, name),
    );
  }
  return lines.join("\n") + "\n";
}

function exportName(name: string) {
  return isIdentifier(name) ? name : JSON.stringify(name);
}

function exportList(local: string, name: string) {
  return local === name
    ? `export { ${local} };`
    : `export { ${local} as ${JSON.stringify(name)} };`;
}

type FunctionDeclaration = { local: string; params: string; results: string };

/** TypeScript declarations of a module's exports, as JS sees them through ESM integration. */
function exportTypes(module: Module): string {
  const lines = ["// Generated by wasmati build: the exports of the Wasm module."];
  for (const [i, { name }] of module.exports.entries()) {
    const declaration = exportDeclarations(module)[i];
    const text =
      "params" in declaration
        ? `declare function ${declaration.local}(${declaration.params}): ${declaration.results};`
        : `declare const ${declaration.local}: ${declaration.type};`;
    lines.push(text, exportList(declaration.local, name));
  }
  return lines.join("\n") + "\n";
}

/** Each export's local name and type, or parameters and results. */
function exportDeclarations(
  module: Module,
): (FunctionDeclaration | { local: string; type: string })[] {
  const imported = (kind: string) =>
    module.imports
      .filter(({ description }) => description.kind === kind)
      .map(({ description }) => description.value);
  const functionTypes = [
    ...imported("function").map((typeIdx) => module.types[typeIdx as number]),
    ...module.funcs.map(({ typeIdx }) => module.types[typeIdx]),
  ];
  const globals = [...imported("global"), ...module.globals.map(({ type }) => type)] as {
    value: ValueType;
  }[];
  return module.exports.map(({ name, description }, i) => {
    const local = isIdentifier(name) ? name : `export${i}`;
    switch (description.kind) {
      case "function": {
        const type = functionTypes[description.value];
        if (type === undefined || !isFunctionType(type))
          throw Error(`export "${name}" is not a function`);
        const names = (module.names?.locals?.[description.value] ?? {}) as Record<number, string>;
        return { local, params: parameters(type, names), results: results(type) };
      }
      case "global":
        // Exported globals are their values at instantiation.
        return { local, type: jsType(globals[description.value].value) };
      case "memory":
        return { local, type: "WebAssembly.Memory" };
      case "table":
        return { local, type: "WebAssembly.Table" };
      case "tag":
        return { local, type: "WebAssembly.Tag" };
    }
  });
}

function parameters(type: FunctionType, names: Record<number, string>) {
  return type.args
    .map((arg, i) => {
      const name = names[i];
      return `${name !== undefined && isIdentifier(name) ? name : `arg${i}`}: ${jsType(arg)}`;
    })
    .join(", ");
}

function results({ results }: FunctionType) {
  if (results.length === 0) return "void";
  if (results.length === 1) return jsType(results[0]);
  return `[${results.map(jsType).join(", ")}]`;
}

/** Numbers are numbers, except i64 as bigint; references are opaque, except functions. */
function jsType(type: ValueType): string {
  if (type === "i32" || type === "f32" || type === "f64") return "number";
  if (type === "i64") return "bigint";
  if (type === "v128") return "never";
  if (type === "funcref") return "Function | null";
  return "unknown";
}
